import { HttpClient, HttpHeaders, HttpParams } from '@angular/common/http';
import { Injectable, inject } from '@angular/core';
import { Observable, map } from 'rxjs';

import type { PaymentStatus, PaymentTenderMethod } from '@app/shared/models/dto/payments/payment-method';
import type { PaymentResponse } from '@app/shared/models/dto/payments/payment-response';
import type { PaymentSummaryResponse } from '@app/shared/models/dto/payments/payment-summary-response';
import type { PendingOrderResponse } from '@app/shared/models/dto/payments/pending-order-response';
import type { RegisterPaymentRequest } from '@app/shared/models/dto/payments/register-payment-request';
import type { VoidPaymentRequest } from '@app/shared/models/dto/payments/void-payment-request';
import {
  type Page,
  type PageEnvelope,
  unwrapPage,
} from '@app/shared/models/dto/common/pagination';

/** Query for the pending board (`GET /v1/payments/pending`). */
export interface PendingPaymentsQuery {
  /** Business date (`YYYY-MM-DD`); the backend defaults to today. */
  date?: string;
  /** Exact order id or table number (numeric only). */
  search?: string;
  page?: number;
  size?: number;
}

/** Query for the payment journal (`GET /v1/payments`). */
export interface PaymentJournalQuery {
  date?: string;
  method?: PaymentTenderMethod;
  status?: PaymentStatus;
  page?: number;
  size?: number;
}

/** Default page size for the cashier board and journal. */
export const DEFAULT_PAYMENTS_PAGE_SIZE = 20;

function buildParams(values: readonly [string, string | number | undefined][]): HttpParams {
  let params = new HttpParams();
  for (const [key, value] of values) {
    if (value !== undefined && value !== '') {
      params = params.set(key, String(value));
    }
  }
  return params;
}

/**
 * Typed client for the payments slice.
 *
 * Endpoints (payments backend lane, envelope `{ data }` unwrapped by the
 * envelope interceptor):
 *
 *  - `GET  /v1/payments/pending`
 *  - `POST /v1/payments` with `Idempotency-Key`
 *  - `GET  /v1/payments/{id}`
 *  - `GET  /v1/payments`
 *  - `POST /v1/payments/{id}/void`
 *
 * The charge request never carries a total: the server recomputes the
 * subtotal. The idempotency key is generated by the caller per attempt and
 * reused on retry.
 */
@Injectable({ providedIn: 'root' })
export class Payment {
  private readonly http = inject(HttpClient);

  /** Delivered orders of a business date that still owe money. */
  getPending(query: PendingPaymentsQuery = {}): Observable<Page<PendingOrderResponse>> {
    const { date, search, page = 0, size = DEFAULT_PAYMENTS_PAGE_SIZE } = query;
    const params = buildParams([
      ['date', date],
      ['search', search],
      ['page', page],
      ['size', size],
    ]);
    return this.http
      .get<PageEnvelope<PendingOrderResponse>>('v1/payments/pending', { params })
      .pipe(map((response) => unwrapPage<PendingOrderResponse>(response)));
  }

  /**
   * Charges an order.
   *
   * A replay of the same key returns the original payment with `200`; a new
   * charge returns `201`. Both bodies are the same `PaymentResponse`.
   */
  charge(request: RegisterPaymentRequest, idempotencyKey: string): Observable<PaymentResponse> {
    const headers = new HttpHeaders().set('Idempotency-Key', idempotencyKey);
    return this.http.post<PaymentResponse>('v1/payments', request, { headers });
  }

  /** Payment detail and receipt data. */
  getById(id: number): Observable<PaymentResponse> {
    return this.http.get<PaymentResponse>(`v1/payments/${String(id)}`);
  }

  /** Paged payment journal (date, method and status filters). */
  getJournal(query: PaymentJournalQuery = {}): Observable<Page<PaymentSummaryResponse>> {
    const { date, method, status, page = 0, size = DEFAULT_PAYMENTS_PAGE_SIZE } = query;
    const params = buildParams([
      ['date', date],
      ['method', method],
      ['status', status],
      ['page', page],
      ['size', size],
    ]);
    return this.http
      .get<PageEnvelope<PaymentSummaryResponse>>('v1/payments', { params })
      .pipe(map((response) => unwrapPage<PaymentSummaryResponse>(response)));
  }

  /** Full void with a mandatory reason; only while the owning shift is open. */
  voidPayment(id: number, reason: string): Observable<PaymentResponse> {
    const body: VoidPaymentRequest = { reason: reason.trim() };
    return this.http.post<PaymentResponse>(`v1/payments/${String(id)}/void`, body);
  }
}
